import { spawnSync } from 'node:child_process';
import {
  closeSync,
  copyFileSync,
  openSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { buildIdentity, digest, inputIdentity } from './lib/release-evidence-inputs.mjs';
import { validateNativeEvidence } from './lib/release-evidence-native.mjs';
import { captureExpectedScope, validateExpectedScope } from './lib/release-evidence-scope.mjs';
import {
  artifact,
  evidenceDirectory,
  kinds,
  native,
  readReceipt,
  recipe,
  reports,
  root,
  same,
  validateReports,
  validateSourceScope,
} from './lib/release-evidence-store.mjs';

export function run(kind, directory, reuse) {
  const identity = inputIdentity(root);
  if (reuse && kind === 'pre-release') {
    try {
      readReceipt(kind, directory, identity);
      console.log(`Reusing complete matching ${kind} evidence`);
      return;
    } catch {
      console.log(`${kind} evidence absent or no longer valid; executing the required check`);
    }
  }
  const command = recipe(kind, directory);
  const receiptFile = artifact(directory, `${kind}.receipt.json`);
  rmSync(receiptFile, { force: true });
  for (const name of reports(kind)) rmSync(artifact(directory, name), { force: true });
  if (kind === 'unit' || kind === 'e2e') captureExpectedScope(kind, directory, root);
  const beforeBuild = kind === 'e2e' ? buildIdentity(root) : undefined;
  const startedAt = Date.now();
  const log = artifact(directory, `${kind}.log`);
  const logFd = openSync(log, 'w', 0o600);
  const outputFd =
    kind === 'audit' ? openSync(artifact(directory, 'audit.json'), 'w', 0o600) : logFd;
  let result;
  try {
    result = spawnSync(command[0], command.slice(1), {
      cwd: root,
      env: process.env,
      stdio: ['ignore', outputFd, logFd],
    });
  } finally {
    if (outputFd !== logFd) closeSync(outputFd);
    closeSync(logFd);
  }
  if (result.error || result.signal || result.status !== 0) {
    throw new Error(`${kind} failed; execution log: ${log}`);
  }
  if (!same(identity, inputIdentity(root)))
    throw new Error('Source or environment changed during verification');
  if (kind === 'pre-release') {
    const build = statSync(join(root, 'apps/web/.next/BUILD_ID'));
    if (!build.isFile() || build.mtimeMs < startedAt) {
      throw new Error('Pre-release did not produce a fresh application build');
    }
  }
  const copies =
    kind === 'unit'
      ? [['apps/web/coverage/coverage-final.json', 'coverage.json']]
      : kind === 'e2e'
        ? [['apps/web/test-results/pw-results.json', 'e2e.json']]
        : [];
  for (const [source, target] of copies) {
    const file = join(root, source);
    if (!statSync(file).isFile() || statSync(file).mtimeMs < startedAt)
      throw new Error('Native report was not generated by this execution');
    copyFileSync(file, artifact(directory, target));
  }
  validateReports(kind, directory);
  validateSourceScope(kind, directory, identity.root);
  if (kind === 'unit' || kind === 'e2e') validateExpectedScope(kind, directory, identity.root);
  const reportHashes = Object.fromEntries(
    reports(kind).map((name) => [name, digest(readFileSync(artifact(directory, name)))]),
  );
  const buildAfter = ['pre-release', 'e2e'].includes(kind) ? buildIdentity(root) : undefined;
  writeFileSync(
    receiptFile,
    JSON.stringify(
      {
        version: 1,
        kind,
        exitCode: 0,
        identity,
        command,
        startedAt,
        finishedAt: Date.now(),
        reportHashes,
        buildBefore: beforeBuild,
        buildAfter,
      },
      null,
      2,
    ),
    { mode: 0o600 },
  );
  console.log(`${kind} passed; bound execution receipt recorded`);
}

export function collect(directory, identity = inputIdentity(root)) {
  const receipts = kinds.map((kind) => readReceipt(kind, directory, identity));
  const summary = validateNativeEvidence({
    unit: native(directory, 'unit.json'),
    coverage: native(directory, 'coverage.json'),
    e2e: native(directory, 'e2e.json'),
    audit: native(directory, 'audit.json'),
  });
  const version = JSON.parse(readFileSync(join(identity.root, 'package.json'), 'utf8')).version;
  const core = typeof version === 'string' ? version.match(/^\d+\.\d+\.\d+/)?.[0] : undefined;
  if (!core || (version !== core && !/^[+-][A-Za-z0-9.+-]+$/.test(version.slice(core.length))))
    throw new Error('Invalid release version');
  const output = artifact(
    directory,
    `evidence-pack-${version}-${identity.revision.slice(0, 8)}.md`,
  );
  const text = [
    '# Native Release Verification Evidence',
    '',
    `Version: ${version} | Git anchor: ${identity.revision}`,
    `Working-tree snapshot: ${identity.source}`,
    'The snapshot includes uncommitted inputs and local configuration; the Git anchor alone is not the tested snapshot.',
    `Node: ${identity.node} | pnpm: ${identity.pnpm}`,
    '',
    ...receipts.map(
      (receipt) => `- ${receipt.kind}: passed at ${new Date(receipt.finishedAt).toISOString()}`,
    ),
    '',
    `Unit: ${summary.unit.passed} passed, ${summary.unit.skipped} existing skips.`,
    `Browser: ${summary.e2e.passed} expected, ${summary.e2e.flaky} flaky, ${summary.e2e.skipped} skipped.`,
    ...['branches', 'statements', 'functions', 'lines'].map((key) => {
      const metric = summary.coverage.metrics[key];
      return `Coverage ${key}: ${metric.covered}/${metric.total} (${metric.pct}%).`;
    }),
    `Dependency audit: high ${summary.audit.high}, critical ${summary.audit.critical}, moderate ${summary.audit.moderate}, low ${summary.audit.low}.`,
    '',
    'This records the specified verification executions, not deployment or live Sentry resolution.',
    'Each release gate runs unit and browser tests afresh; collection never reruns them.',
    'Policy and dependency advisories must be current within one hour.',
    '',
  ].join('\n');
  writeFileSync(output, text, { mode: 0o600 });
  return output;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const [action, first, second, ...extra] = process.argv.slice(2);
    if (extra.length) throw new Error('Unexpected evidence arguments');
    if (action === 'collect' && first && second === undefined) {
      console.log(collect(evidenceDirectory(first)));
    } else if (['run', 'reuse-or-run'].includes(action) && kinds.includes(first) && second) {
      run(first, evidenceDirectory(second, true), action === 'reuse-or-run');
    } else
      throw new Error(
        'Usage: release-native-evidence.mjs collect <directory> | run|reuse-or-run <check> <directory>',
      );
  } catch (error) {
    console.error(
      'Release evidence rejected:',
      error instanceof Error ? error.message : 'invalid evidence',
    );
    process.exitCode = 1;
  }
}
